var update = flag.Bool("update", false, "rewrite docs/architecture.md from the code")

// A ring is one layer of the architecture. A package belongs to the first
// ring, in this order, whose patterns match it.
type ring struct {
	id, name string
	pkgs     []string
}

var rings = []ring{
	{"main", "Main", ringMain},
	{"driving", "Driving adapters", ringDriving},
	{"usecases", "Use cases", []string{mod + "internal/billing/..."}},
	{"entities", "Entities", []string{mod + "internal/invoice", mod + "internal/numbering", mod + "internal/epc", mod + "internal/money"}},
	{"driven", "Driven adapters", ringDriven},
	{"libraries", "Libraries", ringLibraries},
}

// testRing holds the packages only tests import. It is matched before the
// rings above, since factory/... also covers factorytest.
var testRing = ring{"tests", "Test support", concat(testSupport, []string{mod + "internal/factory/factorytest"})}

// The packages the architecture leaves out: the architecture tests themselves.
var unplaced = []string{mod + "internal/archtest"}

const docPath = "docs/architecture.md"

// TestArchitectureDoc keeps docs/architecture.md equal to what the code says:
// the rings and imports from go list, the ports and use cases from the type
// checker. Run with -update after a change that moves either.
func TestArchitectureDoc(t *testing.T) {
	t.Parallel()

	got := renderArchitecture(t)
	file := filepath.Join("..", "..", filepath.FromSlash(docPath))
	if *update {
		if err := os.WriteFile(file, got, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	want, err := os.ReadFile(file)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("%s is stale; run: go test ./internal/archtest -run TestArchitectureDoc -update", docPath)
	}
}

func ringOf(importPath string) (ring, bool) {
	if matchesAny(testRing.pkgs, importPath) {
		return testRing, true
	}
	for _, r := range rings {
		if matchesAny(r.pkgs, importPath) {
			return r, true
		}
	}
	return ring{}, false
}

// node is how a package appears in the doc: without the module and
// internal/ prefixes, and with every command package folded into cmd/**.
func node(importPath string) string {
	p := strings.TrimPrefix(importPath, mod)
	if strings.HasPrefix(p, "internal/cmd/") {
		return "cmd/**"
	}
	return strings.TrimPrefix(p, "internal/")
}

func mermaidID(name string) string {
	return strings.NewReplacer("/", "_", ".", "_", "*", "x").Replace(name)
}

type architecture struct {
	pkgs     []pkg // the module's packages, sorted, archtest left out
	commands int
	ports    []port
	compiler port
	useCases []useCase
}

type port struct {
	owner, name  string
	methods      []string // "Load(path string) (invoice.Invoice, error)"
	implementers []string // "store.Store"
	users        []string // driven types that hold the port in a field: "latex.Renderer"
}

type useCase struct {
	name     string
	commands []string // "cmd/invoice/build"
	calls    []string // "Invoices.Load"
}

func renderArchitecture(t *testing.T) []byte {
	t.Helper()

	a := loadArchitecture(t)
	var b bytes.Buffer
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	w("# invox architecture\n\n")
	w("<!-- Generated by TestArchitectureDoc in internal/archtest. Do not edit; run\n")
	w("     go test ./internal/archtest -run TestArchitectureDoc -update -->\n\n")
	w("The code follows the clean architecture of `docs/design/target/README.md`. Source\n")
	w("dependencies point inward, from main to the adapters to the use cases to the\n")
	w("entities. This page is generated from the code, so it shows what is there now.\n")
	w("The import rules at the end are the ones `internal/archtest` and depguard enforce.\n")
	w("To plan a change against it, follow `.claude/skills/invox-architecture/SKILL.md`.\n\n")

	w("## Rings\n\n")
	w("Each arrow is at least one direct import; the label counts the package imports.\n\n")
	w("```mermaid\nflowchart TD\n")
	for _, r := range append(slices.Clone(rings), testRing) {
		w("  %s[\"%s\"]\n", r.id, r.name)
	}
	ringEdges := map[[2]string]int{}
	for _, p := range a.pkgs {
		from, _ := ringOf(p.ImportPath)
		for _, imp := range moduleImports(p) {
			to, _ := ringOf(imp)
			if from.id != to.id {
				ringEdges[[2]string{from.id, to.id}]++
			}
		}
	}
	for _, e := range sortedKeys(ringEdges) {
		w("  %s -->|%d| %s\n", e[0], ringEdges[e], e[1])
	}
	w("```\n\n")

	w("## Packages\n\n")
	w("Direct imports between the release binary's packages. The %d command packages are\n", a.commands)
	w("folded into `cmd/**`. Imports of the libraries and the test support packages are\n")
	w("in the table below.\n\n")
	w("```mermaid\nflowchart TD\n")
	for _, r := range rings {
		if r.id == "libraries" {
			continue
		}
		w("  subgraph %s[\"%s\"]\n", r.id, r.name)
		for _, n := range nodesIn(a.pkgs, r) {
			w("    %s[\"%s\"]\n", mermaidID(n), n)
		}
		w("  end\n")
	}
	edges := map[[2]string]bool{}
	for _, p := range a.pkgs {
		if r, _ := ringOf(p.ImportPath); r.id == "tests" || r.id == "libraries" {
			continue
		}
		for _, imp := range moduleImports(p) {
			if r, _ := ringOf(imp); r.id == "libraries" || node(imp) == node(p.ImportPath) {
				continue
			}
			edges[[2]string{node(p.ImportPath), node(imp)}] = true
		}
	}
	for _, e := range sortedKeys(edges) {
		w("  %s --> %s\n", mermaidID(e[0]), mermaidID(e[1]))
	}
	w("```\n\n")

	w("| Package | Ring | Imports from the module |\n|---|---|---|\n")
	for _, p := range a.pkgs {
		r, _ := ringOf(p.ImportPath)
		var imps []string
		for _, imp := range moduleImports(p) {
			imps = append(imps, strings.TrimPrefix(imp, mod))
		}
		w("| `%s` | %s | %s |\n", strings.TrimPrefix(p.ImportPath, mod), r.name, codeList(imps))
	}
	w("\n")

	w("## Ports\n\n")
	w("The use cases reach the outside only through these interfaces. `billing` owns the\n")
	w("five ports; `render/latex` owns the compiler it builds PDFs with.\n\n")
	w("```mermaid\nclassDiagram\n  direction LR\n")
	var impls []string
	for _, p := range append(slices.Clone(a.ports), a.compiler) {
		for _, impl := range slices.Concat(p.implementers, p.users) {
			if !slices.Contains(impls, impl) {
				impls = append(impls, impl)
				w("  class %s[\"%s\"]\n", mermaidID(impl), impl)
			}
		}
	}
	for _, p := range append(slices.Clone(a.ports), a.compiler) {
		id := mermaidID(p.owner + "." + p.name)
		w("  class %s[\"%s.%s\"] {\n    <<interface>>\n", id, p.owner, p.name)
		for _, m := range p.methods {
			name, _, _ := strings.Cut(m, "(")
			w("    %s()\n", name)
		}
		w("  }\n")
		for _, impl := range p.implementers {
			w("  %s <|.. %s\n", id, mermaidID(impl))
		}
		for _, user := range p.users {
			w("  %s --> %s : uses\n", mermaidID(user), id)
		}
	}
	w("```\n\n")
	for _, p := range append(slices.Clone(a.ports), a.compiler) {
		w("**%s.%s**, implemented by %s:\n\n```go\n", p.owner, p.name, codeList(p.implementers))
		for _, m := range p.methods {
			w("%s\n", m)
		}
		w("```\n\n")
	}

	w("## Use cases\n\n")
	w("Each use case is one method on `billing.Service`. \"Commands\" are the packages under\n")
	w("`internal/cmd` that call it; \"Port methods\" are every port method it reaches,\n")
	w("through `billing`'s own helpers too.\n\n")
	w("| Use case | Commands | Port methods |\n|---|---|---|\n")
	for _, u := range a.useCases {
		w("| `%s` | %s | %s |\n", u.name, codeList(u.commands), codeList(u.calls))
	}
	w("\n")

	w("## Import rules\n\n")
	w("`internal/archtest` fails when one of these breaks; `.golangci.yml` states the\n")
	w("same rules for depguard, one file at a time.\n\n")
	for _, r := range rules {
		w("- %s\n", r.name)
	}
	return b.Bytes()
}

func loadArchitecture(t *testing.T) architecture {
	t.Helper()

	var a architecture
	for _, p := range loadGraph(t) {
		if p.Standard || !strings.HasPrefix(p.ImportPath, mod) || matchesAny(unplaced, p.ImportPath) {
			continue
		}
		if _, ok := ringOf(p.ImportPath); !ok {
			t.Fatalf("%s is in no ring; add it to one in archtest_test.go", p.ImportPath)
		}
		if strings.HasPrefix(p.ImportPath, mod+"internal/cmd/") {
			a.commands++
		}
		a.pkgs = append(a.pkgs, p)
	}
	slices.SortFunc(a.pkgs, func(x, y pkg) int { return strings.Compare(x.ImportPath, y.ImportPath) })

	imp := importer.ForCompiler(token.NewFileSet(), "source", nil)
	billing := importPkg(t, imp, mod+"internal/billing")
	latex := importPkg(t, imp, mod+"internal/render/latex")
	var driven []*types.Package
	for _, p := range a.pkgs {
		if r, _ := ringOf(p.ImportPath); r.id == "driven" {
			driven = append(driven, importPkg(t, imp, p.ImportPath))
		}
	}
	for _, name := range []string{"Invoices", "Directory", "Archive", "Renderer", "Mailer"} {
		a.ports = append(a.ports, describePort(billing, name, driven))
	}
	a.compiler = describePort(latex, "Compiler", driven)

	callers := map[string][]string{}
	for _, p := range a.pkgs {
		if !strings.HasPrefix(p.ImportPath, mod+"internal/cmd/") {
			continue
		}
		cmd := strings.TrimPrefix(p.ImportPath, mod+"internal/")
		for _, m := range serviceCalls(t, imp, p) {
			callers[m] = append(callers[m], cmd)
		}
	}
	for _, uc := range portCalls(t, imp) {
		uc.commands = callers[uc.name]
		a.useCases = append(a.useCases, uc)
	}
	return a
}

func importPkg(t *testing.T, imp types.Importer, path string) *types.Package {
	t.Helper()
	p, err := imp.Import(path)
	if err != nil {
		t.Fatalf("type-check %s: %v", path, err)
	}
	return p
}

// describePort lists the methods of owner's interface name, with their
// signatures, and the exported types in driven that implement it.
func describePort(owner *types.Package, name string, driven []*types.Package) port {
	iface := owner.Scope().Lookup(name).Type().Underlying().(*types.Interface)
	qual := func(p *types.Package) string {
		if p == owner {
			return ""
		}
		return p.Name()
	}
	p := port{owner: owner.Name(), name: name}
	for i := range iface.NumMethods() {
		m := iface.Method(i)
		p.methods = append(p.methods, m.Name()+strings.TrimPrefix(types.TypeString(m.Type(), qual), "func"))
	}
	for _, d := range driven {
		for _, n := range d.Scope().Names() {
			tn, ok := d.Scope().Lookup(n).(*types.TypeName)
			if !ok || !tn.Exported() || types.IsInterface(tn.Type()) {
				continue
			}
			if types.Implements(tn.Type(), iface) || types.Implements(types.NewPointer(tn.Type()), iface) {
				p.implementers = append(p.implementers, d.Name()+"."+n)
			}
			if st, ok := tn.Type().Underlying().(*types.Struct); ok {
				for i := range st.NumFields() {
					if types.Identical(st.Field(i).Type(), owner.Scope().Lookup(name).Type()) {
						p.users = append(p.users, d.Name()+"."+n)
					}
				}
			}
		}
	}
	return p
}

// serviceCalls type-checks the package p and returns the billing.Service
// methods it calls.
func serviceCalls(t *testing.T, imp types.Importer, p pkg) []string {
	t.Helper()

	fset := token.NewFileSet()
	var files []*ast.File
	for _, name := range p.GoFiles {
		f, err := parser.ParseFile(fset, filepath.Join(p.Dir, name), nil, 0)
		if err != nil {
			t.Fatal(err)
		}
		files = append(files, f)
	}
	info := &types.Info{Uses: map[*ast.Ident]types.Object{}}
	if _, err := (&types.Config{Importer: imp}).Check(p.ImportPath, fset, files, info); err != nil {
		t.Fatalf("type-check %s: %v", p.ImportPath, err)
	}
	var methods []string
	for _, obj := range info.Uses {
		if isServiceMethod(obj) && !slices.Contains(methods, obj.Name()) {
			methods = append(methods, obj.Name())
		}
	}
	return methods
}

func isServiceMethod(obj types.Object) bool {
	fn, ok := obj.(*types.Func)
	if !ok || fn.Pkg() == nil || fn.Pkg().Path() != mod+"internal/billing" {
		return false
	}
	recv := fn.Type().(*types.Signature).Recv()
	if recv == nil {
		return false
	}
	t := recv.Type()
	if ptr, ok := t.(*types.Pointer); ok {
		t = ptr.Elem()
	}
	named, ok := t.(*types.Named)
	return ok && named.Obj().Name() == "Service"
}

// portCalls type-checks billing and returns, for each exported Service
// method, the port methods it calls directly or through billing's other
// functions.
func portCalls(t *testing.T, imp types.Importer) []useCase {
	t.Helper()

	dir := filepath.Join("..", "billing")
	entries, err := os.ReadDir(dir)
	if err != nil {
		t.Fatal(err)
	}
	fset := token.NewFileSet()
	var files []*ast.File
	for _, e := range entries {
		if !strings.HasSuffix(e.Name(), ".go") || strings.HasSuffix(e.Name(), "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, e.Name()), nil, 0)
		if err != nil {
			t.Fatal(err)
		}
		files = append(files, f)
	}
	info := &types.Info{Defs: map[*ast.Ident]types.Object{}, Uses: map[*ast.Ident]types.Object{}}
	billing, err := (&types.Config{Importer: imp}).Check(mod+"internal/billing", fset, files, info)
	if err != nil {
		t.Fatalf("type-check billing: %v", err)
	}

	portMethod := map[types.Object]string{}
	for name := range narrowPorts {
		iface := billing.Scope().Lookup(name).Type().Underlying().(*types.Interface)
		for i := range iface.NumMethods() {
			portMethod[iface.Method(i)] = name + "." + iface.Method(i).Name()
		}
	}
	calls := map[types.Object][]types.Object{}
	var service []*types.Func
	for _, f := range files {
		for _, decl := range f.Decls {
			fd, ok := decl.(*ast.FuncDecl)
			if !ok || fd.Body == nil {
				continue
			}
			fn := info.Defs[fd.Name].(*types.Func)
			if fn.Exported() && isServiceMethod(fn) {
				service = append(service, fn)
			}
			ast.Inspect(fd.Body, func(n ast.Node) bool {
				if id, ok := n.(*ast.Ident); ok {
					if obj, ok := info.Uses[id].(*types.Func); ok && (obj.Pkg() == billing || portMethod[obj] != "") {
						calls[fn] = append(calls[fn], obj)
					}
				}
				return true
			})
		}
	}

	var out []useCase
	for _, fn := range service {
		seen := map[types.Object]bool{}
		var reached []string
		var walk func(types.Object)
		walk = func(obj types.Object) {
			if seen[obj] {
				return
			}
			seen[obj] = true
			if name := portMethod[obj]; name != "" {
				reached = append(reached, name)
				return
			}
			for _, next := range calls[obj] {
				walk(next)
			}
		}
		walk(fn)
		slices.Sort(reached)
		out = append(out, useCase{name: fn.Name(), calls: reached})
	}
	slices.SortFunc(out, func(x, y useCase) int { return strings.Compare(x.name, y.name) })
	return out
}

func moduleImports(p pkg) []string {
	var out []string
	for _, imp := range p.Imports {
		if strings.HasPrefix(imp, mod) {
			out = append(out, imp)
		}
	}
	return out
}

func nodesIn(pkgs []pkg, r ring) []string {
	var out []string
	for _, p := range pkgs {
		if got, _ := ringOf(p.ImportPath); got.id == r.id && !slices.Contains(out, node(p.ImportPath)) {
			out = append(out, node(p.ImportPath))
		}
	}
	return out
}

func codeList(items []string) string {
	if len(items) == 0 {
		return "none"
	}
	quoted := make([]string, len(items))
	for i, s := range items {
		quoted[i] = "`" + s + "`"
	}
	return strings.Join(quoted, ", ")
}

func sortedKeys[V any](m map[[2]string]V) [][2]string {
	keys := make([][2]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	slices.SortFunc(keys, func(x, y [2]string) int {
		if c := strings.Compare(x[0], y[0]); c != 0 {
			return c
		}
		return strings.Compare(x[1], y[1])
	})
	return keys
}
